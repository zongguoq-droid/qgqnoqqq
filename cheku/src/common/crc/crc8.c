/**
 * @file    crc8.c
 * @brief   CRC8 校验算法 - 实现
 *
 * CRC8 算法有两种常见实现方式:
 *
 * 1. 逐位计算法 (Bit-by-bit)
 *    原理: 模拟多项式长除法，对每个数据位逐位处理。
 *    优点: 代码极小，不需要查找表
 *    缺点: 速度慢 (每个字节循环8次), O(8n) 时间复杂度
 *
 * 2. 查表法 (Table-driven) ← 本实现采用
 *    原理: 预先计算 0x00~0xFF 每个字节的 CRC 值存入查找表，
 *         运行时只需一次查表+异或操作。
 *    优点: 速度快 O(n), 每个字节只需 1次查表 + 1次异或
 *    缺点: 需要 256 字节存储查找表
 *
 * 对于 528MHz 的嵌入式 CPU，256字节查找表完全可以接受。
 * 查找表在编译期计算好 (static const)，不占用 RAM (在 .rodata 段)。
 *
 * CRC8 多项式 0x07 (x^8 + x^2 + x + 1) 的数学含义:
 *   二进制: 0000 0111 → 对应多项式 x^8 + x^2 + x + 1
 *   这里的 x^8 是隐含的 (8次项系数总是1，不存储)
 *   实际使用的除数是 9位: 1 0000 0111
 *
 * 查表法原理简述:
 *   crc_new = table[(crc_old ^ byte) & 0xFF]
 *   其中 table[val] = 预先计算好的 CRC8(val)
 *
 * 学习要点:
 *   1. 有限域 GF(2) 上的运算 (加 = XOR, 乘除 = 位移+XOR)
 *   2. 查表法: 编译期计算 → 静态只读数据 → 运行期 O(1) 查表
 *   3. CRC 多项式的选择: 不同多项式检错能力不同
 */

