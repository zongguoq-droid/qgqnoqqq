/**
 * @brief 计算 CRC8 校验值 (查表法)
 *
 * 算法过程 (伪代码):
 *   crc = initial_value
 *   for each byte in data:
 *       index = (crc ^ byte) & 0xFF    // 取低8位作为查表索引
 *       crc   = table[index]           // 查表得到新的 CRC
 *   return crc
 *
 * 为什么有效?
 *   查表法的核心是: 对于任意 crc 和新输入 byte，
 *   新的 CRC 可以通过一次查表得到 (这是多项式除法的数学性质)。
 *
 * @param data  数据指针
 * @param len   数据长度
 * @param crc   当前 CRC 值 (首次调用传 0x00)
 * @return      更新后的 CRC 值
 */
uint8_t crc8_calculate(const uint8_t *data, size_t len, uint8_t crc)
{
    size_t i;

    /* 参数检查 */
    if (!data || len == 0) {
        return crc;  /* 空数据 = CRC 不变 */
    }

    for (i = 0; i < len; i++) {
        /* 核心查表操作:
         *   1. crc ^ data[i] = 将新字节与当前 CRC 异或
         *   2. & 0xFF = 取低 8 位作为查表索引
         *   3. crc8_table[...] = 查表得到新 CRC
         *
         * 为什么是 ^ (异或)?
         *   CRC 本质是 GF(2) 多项式除法，GF(2) 的加法 = 异或 */
        crc = crc8_table[(crc ^ data[i]) & 0xFF];
    }

    return crc;
}
